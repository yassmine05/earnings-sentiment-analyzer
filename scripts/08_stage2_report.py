"""Stage 2, step 2: sanity checks, the timing spike check by bucket, figures and docs/stage2_event_study.md.

Inputs   results/stage2/event_cars.csv, ar_by_relday.csv, ar_by_relday_changed_events_8k_clock.csv
Outputs  results/stage2/*.csv tables, results/stage2/figures/*.png, docs/stage2_event_study.md
Every number in the report is computed here.
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from earnings_sentiment import config
from earnings_sentiment import eventstudy as es

OUT = config.RESULTS / "stage2"
FIG = OUT / "figures"
BUCKETS = ["pre-open", "market hours", "after close"]
COLOR = {"pre-open": "#2a78d6", "market hours": "#eb6834", "after close": "#1baf7a"}
MARKER = {"pre-open": "o", "market hours": "s", "after close": "^"}
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
PLOT_REL = (-10, 10)

plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": GRID, "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
    "text.color": INK, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
    "axes.spines.top": False, "axes.spines.right": False, "font.size": 10, "axes.titlesize": 11,
    "axes.titleweight": "bold", "axes.titlelocation": "left", "lines.linewidth": 2, "lines.markersize": 5,
})


def md(df: pd.DataFrame, floatfmt: str = "{:.2f}") -> list[str]:
    out = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "|".join(["---"] * len(df.columns)) + "|"]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, (float, np.floating)):
                cells.append("" if np.isnan(v) else floatfmt.format(v))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return out


def by_rel(long: pd.DataFrame) -> pd.DataFrame:
    g = long.groupby("rel")
    t = pd.DataFrame({
        "n": g["ar"].count(),
        "mean_ar_bp": g["ar"].mean() * 1e4,
        "t_stat": g["ar"].mean() / (g["ar"].std() / np.sqrt(g["ar"].count())),
        "mean_abs_ar_bp": g["ar"].apply(lambda s: s.abs().mean()) * 1e4,
        "mean_abs_sar": g["sar"].apply(lambda s: s.abs().mean()),
        "mean_abn_log_volume": g["abn_log_volume"].mean(),
    })
    return t.reset_index()


def peak(t: pd.DataFrame, col: str, lo: int = -5, hi: int = 5) -> int:
    w = t[(t["rel"] >= lo) & (t["rel"] <= hi)]
    return int(w.loc[w[col].idxmax(), "rel"])


def panel_by_bucket(tabs: dict, col: str, ylabel: str, title: str, path, scale: float = 1.0) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(11, 3.4), sharey=True)
    for ax, b in zip(axes, BUCKETS):
        t = tabs[b]
        t = t[(t["rel"] >= PLOT_REL[0]) & (t["rel"] <= PLOT_REL[1])]
        ax.axvline(0, color=INK2, linewidth=1, linestyle=(0, (3, 3)))
        ax.plot(t["rel"], t[col] * scale, color=COLOR[b], marker=MARKER[b])
        pk = t.loc[t[col].idxmax()]
        ax.annotate(f"peak: day {int(pk['rel']):+d}" if pk["rel"] else "peak: day 0",
                    (pk["rel"], pk[col] * scale), textcoords="offset points", xytext=(8, -2), color=INK, fontsize=9)
        ax.set_title(f"{b} (n = {int(t['n'].max())})")
        ax.set_xlabel("trading days relative to day 0")
        ax.set_xticks(range(-10, 11, 5))
    axes[0].set_ylabel(ylabel)
    fig.suptitle(title, x=0.01, ha="left", fontsize=12, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    cars = pd.read_csv(OUT / "event_cars.csv")
    long = pd.read_csv(OUT / "ar_by_relday.csv")
    long8 = pd.read_csv(OUT / "ar_by_relday_changed_events_8k_clock.csv")
    key = ["ticker", "accession"]
    long = long.merge(cars[key + ["event_bucket", "event_time_changed", "accepted_et", "sector"]], on=key)

    L = ["# Stage 2: event study and timing check", "",
         "Generated by `scripts/08_stage2_report.py` from the outputs of `scripts/07_event_study.py`. "
         "Every number is computed by that code.", "",
         "## 1. Method", "",
         f"- Events: **{len(cars)}** earnings releases of {cars['ticker'].nunique()} firms, day 0 from the approved event clock.",
         "- Returns: simple daily returns from dividend- and split-adjusted closes.",
         f"- Primary model: market model on SPY, estimated over relative days [{es.EST_START}, {es.EST_END}] "
         f"(at least {es.EST_MIN_OBS} observations). AR = R - (alpha + beta x R_SPY).",
         "- Robustness models computed alongside: Fama-French 3 factors plus momentum (`_ff4`), and a market model "
         "on the firm's sector ETF (`_sector`).",
         "- CAR[a,b] is the sum of daily ARs. Reaction family: CAR[0,+1] to CAR[0,+5]. Drift family: AR[+1], CAR[+1,+2] to CAR[+1,+5].",
         "- Abnormal volume: log volume minus the mean log volume of the estimation window.",
         "- The 10 spin-off and merger adjustment days listed in `docs/stage1_price_artifacts.md` are removed from "
         "estimation windows. None falls inside an event window [-1, +5].",
         "- Earlier earnings dates of the same firm sit inside the estimation window and are not removed. "
         "This is standard and makes the residual volatility slightly conservative.", ""]

    # ---- 2 estimation diagnostics --------------------------------------------
    d = cars[["n_est", "alpha", "beta", "r2", "sigma"]].describe().T[["min", "25%", "50%", "75%", "max"]].reset_index()
    d = d.rename(columns={"index": "quantity"})
    L += ["## 2. Estimation diagnostics (market model)", "",
          f"Events with fewer than {es.EST_MIN_OBS} estimation observations: **{int((~cars['est_ok']).sum())}**. "
          f"Events with a missing AR inside [-1, +5]: **{int(cars['missing_ar_m1_p5'].sum())}**.", ""]
    L += md(d, "{:.4f}") + [""]

    # ---- 3 sanity: AR by relative day -----------------------------------------
    allt = by_rel(long)
    allt.to_csv(OUT / "ar_by_relday_summary.csv", index=False)
    show = allt[(allt["rel"] >= -10) & (allt["rel"] <= 10)]
    base = allt[(allt["rel"] >= -10) & (allt["rel"] <= -2)]
    d0 = allt[allt["rel"] == 0].iloc[0]
    L += ["## 3. Sanity check: abnormal returns by relative day (all events)", "",
          "The t-statistic is a plain cross-sectional one (no clustering); it is a sanity check, not a result.", ""]
    L += md(show.rename(columns={"rel": "day"}), "{:.2f}") + [""]
    L += [f"- Mean AR over days [-10, -2]: **{base['mean_ar_bp'].mean():.2f} bp** per day "
          f"(largest absolute t-statistic among those days: {base['t_stat'].abs().max():.2f}).",
          f"- Mean absolute AR on day 0: **{d0['mean_abs_ar_bp']:.0f} bp**, against **{base['mean_abs_ar_bp'].mean():.0f} bp** "
          f"on days [-10, -2], a ratio of **{d0['mean_abs_ar_bp'] / base['mean_abs_ar_bp'].mean():.2f}**.",
          f"- Mean abnormal log volume on day 0: **{d0['mean_abn_log_volume']:.2f}** "
          f"(volume about {np.exp(d0['mean_abn_log_volume']):.2f} times normal), against "
          f"{base['mean_abn_log_volume'].mean():.2f} on days [-10, -2].", "",
          "![Mean abnormal return and cumulative average abnormal return](../results/stage2/figures/caar.png)", ""]

    fig, axes = plt.subplots(1, 2, figsize=(11, 3.6))
    se = show["mean_ar_bp"] / show["t_stat"]
    axes[0].axhline(0, color=INK2, linewidth=1)
    axes[0].vlines(show["rel"], show["mean_ar_bp"] - 1.96 * se, show["mean_ar_bp"] + 1.96 * se, color=COLOR["pre-open"], linewidth=2)
    axes[0].plot(show["rel"], show["mean_ar_bp"], "o", color=COLOR["pre-open"])
    axes[0].set_title("Mean abnormal return by day (bars: 95% interval)")
    axes[0].set_ylabel("basis points")
    caar = show["mean_ar_bp"].cumsum()
    axes[1].axhline(0, color=INK2, linewidth=1)
    axes[1].plot(show["rel"], caar, marker="o", color=COLOR["pre-open"])
    axes[1].set_title("Cumulative average abnormal return from day -10")
    axes[1].set_ylabel("basis points")
    for ax in axes:
        ax.axvline(0, color=INK2, linewidth=1, linestyle=(0, (3, 3)))
        ax.set_xlabel("trading days relative to day 0")
        ax.set_xticks(range(-10, 11, 5))
    fig.tight_layout()
    fig.savefig(FIG / "caar.png", dpi=150)
    plt.close(fig)

    # ---- 4 timing check by bucket ----------------------------------------------
    tabs = {b: by_rel(long[long["event_bucket"] == b]) for b in BUCKETS}
    pd.concat([t.assign(bucket=b) for b, t in tabs.items()]).to_csv(OUT / "timing_check_by_bucket.csv", index=False)
    panel_by_bucket(tabs, "mean_abs_ar_bp", "mean |AR|, basis points",
                    "Mean absolute abnormal return by relative day and timing bucket", FIG / "timing_abs_ar.png")
    panel_by_bucket(tabs, "mean_abn_log_volume", "abnormal log volume",
                    "Mean abnormal volume by relative day and timing bucket", FIG / "timing_abn_volume.png")
    L += ["## 4. Timing check: is the spike on day 0?", "",
          "If the EDGAR-based clock is right, both the absolute abnormal return and abnormal volume should peak on day 0 "
          "in every bucket. A peak on day -1 would mean the news reached the market before our timestamp; a peak on "
          "day +1 would mean day 0 is set one session too early.", "",
          "![Mean absolute abnormal return by bucket](../results/stage2/figures/timing_abs_ar.png)", "",
          "![Mean abnormal volume by bucket](../results/stage2/figures/timing_abn_volume.png)", ""]
    rows = []
    for b in BUCKETS:
        t = tabs[b].set_index("rel")
        rows.append({
            "bucket": b, "events": int(t["n"].max()),
            "|AR| day -1 (bp)": t.loc[-1, "mean_abs_ar_bp"], "|AR| day 0 (bp)": t.loc[0, "mean_abs_ar_bp"],
            "|AR| day +1 (bp)": t.loc[1, "mean_abs_ar_bp"], "|AR| peak day": peak(tabs[b], "mean_abs_ar_bp"),
            "volume day -1": t.loc[-1, "mean_abn_log_volume"], "volume day 0": t.loc[0, "mean_abn_log_volume"],
            "volume day +1": t.loc[1, "mean_abn_log_volume"], "volume peak day": peak(tabs[b], "mean_abn_log_volume"),
        })
    bt = pd.DataFrame(rows)
    bt.to_csv(OUT / "timing_check_peaks.csv", index=False)
    L += md(bt) + [""]

    # where does each event's own largest |AR| in [-3,+3] fall?
    w = long[(long["rel"] >= -3) & (long["rel"] <= 3)].copy()
    w["abs_ar"] = w["ar"].abs()
    own = w.loc[w.groupby(key)["abs_ar"].idxmax(), key + ["rel", "event_bucket"]]
    dist = (own.groupby("event_bucket")["rel"].value_counts(normalize=True).unstack(fill_value=0) * 100).reindex(BUCKETS)
    dist.columns = [f"day {c:+d}" if c else "day 0" for c in dist.columns]
    dist = dist.round(1).reset_index().rename(columns={"event_bucket": "bucket"})
    L += ["Share of events (%) whose own largest absolute AR within [-3, +3] falls on each day "
          "(with 7 days, a pure-noise benchmark is 14.3% per day):", ""] + md(dist, "{:.1f}") + [""]

    # after-close filings accepted at or after 17:30 are disseminated by EDGAR the next business morning
    ac = long[(long["event_bucket"] == "after close") & ~long["event_time_changed"]].copy()
    tt = pd.to_datetime(ac["accepted_et"])
    ac["sub"] = np.where(tt.dt.hour * 60 + tt.dt.minute >= 17 * 60 + 30, "accepted 17:30 or later", "accepted 16:00-17:29")
    rows = []
    for s, g in ac.groupby("sub"):
        t = by_rel(g).set_index("rel")
        rows.append({"after-close sub-group": s, "events": int(t["n"].max()),
                     "|AR| day -1 (bp)": t.loc[-1, "mean_abs_ar_bp"], "|AR| day 0 (bp)": t.loc[0, "mean_abs_ar_bp"],
                     "|AR| day +1 (bp)": t.loc[1, "mean_abs_ar_bp"],
                     "volume day -1": t.loc[-1, "mean_abn_log_volume"], "volume day 0": t.loc[0, "mean_abn_log_volume"],
                     "volume day +1": t.loc[1, "mean_abn_log_volume"]})
    L += ["After-close filings split by acceptance time. Day 0 is the next session for both groups; the split only "
          "checks that late-evening filings behave the same way:", ""] + md(pd.DataFrame(rows)) + [""]

    # per firm
    rows = []
    for tkr, g in long.groupby("ticker"):
        t = by_rel(g)
        ts = t.set_index("rel")
        rows.append({"ticker": tkr, "events": int(ts["n"].max()),
                     "main bucket": g.drop_duplicates(key)["event_bucket"].mode().iloc[0],
                     "|SAR| day -1": ts.loc[-1, "mean_abs_sar"], "|SAR| day 0": ts.loc[0, "mean_abs_sar"],
                     "|SAR| day +1": ts.loc[1, "mean_abs_sar"], "|SAR| peak day": peak(t, "mean_abs_sar", -3, 3),
                     "volume day -1": ts.loc[-1, "mean_abn_log_volume"], "volume day 0": ts.loc[0, "mean_abn_log_volume"],
                     "volume day +1": ts.loc[1, "mean_abn_log_volume"], "volume peak day": peak(t, "mean_abn_log_volume", -3, 3)})
    firm = pd.DataFrame(rows)
    firm.to_csv(OUT / "timing_check_by_firm.csv", index=False)
    off = firm[(firm["|SAR| peak day"] != 0) | (firm["volume peak day"] != 0)]
    L += ["### Per firm", "",
          f"Firms whose mean standardised absolute AR and mean abnormal volume both peak on day 0 (within [-3, +3]): "
          f"**{len(firm) - len(off)} of {len(firm)}**. Firms where either peak is on another day:", ""]
    L += (md(off) if len(off) else ["None."]) + ["", "The full per-firm table is `results/stage2/timing_check_by_firm.csv`.", ""]

    # the 15 clock-adjusted events under both clocks
    chg = long[long["event_time_changed"]]
    a, b8 = by_rel(chg).set_index("rel"), by_rel(long8).set_index("rel")
    cmp_ = pd.DataFrame({
        "day": range(-3, 4),
        "|AR| adjusted clock (bp)": [a.loc[r, "mean_abs_ar_bp"] for r in range(-3, 4)],
        "|AR| 8-K clock (bp)": [b8.loc[r, "mean_abs_ar_bp"] for r in range(-3, 4)],
        "volume adjusted clock": [a.loc[r, "mean_abn_log_volume"] for r in range(-3, 4)],
        "volume 8-K clock": [b8.loc[r, "mean_abn_log_volume"] for r in range(-3, 4)],
    })
    cmp_.to_csv(OUT / "timing_check_changed_events.csv", index=False)
    L += [f"### The {chg.drop_duplicates(key).shape[0]} clock-adjusted events (Berkshire and Linde)", "",
          "Same events, day 0 taken from the adjusted clock (10-Q/10-K acceptance) and from the unadjusted 8-K clock:", ""]
    day = lambda n: "0" if n == 0 else f"{n:+d}"
    L += md(cmp_) + ["",
          f"Peak day of mean |AR|: adjusted clock **{day(peak(a.reset_index(), 'mean_abs_ar_bp', -3, 3))}**, "
          f"8-K clock **{day(peak(b8.reset_index(), 'mean_abs_ar_bp', -3, 3))}**. "
          f"Peak day of abnormal volume: adjusted clock **{day(peak(a.reset_index(), 'mean_abn_log_volume', -3, 3))}**, "
          f"8-K clock **{day(peak(b8.reset_index(), 'mean_abn_log_volume', -3, 3))}**. "
          "With so few events this comparison is indicative only.", ""]

    # ---- 5 CAR summary -----------------------------------------------------------
    rows = []
    for name, a_, b_ in es.CAR_WINDOWS:
        x = cars[name].dropna()
        rows.append({"window": f"[{a_:+d}, {b_:+d}]".replace("+0", "0"), "column": name, "n": len(x),
                     "mean (bp)": x.mean() * 1e4, "median (bp)": x.median() * 1e4, "std (%)": x.std() * 100,
                     "t-stat": x.mean() / (x.std() / np.sqrt(len(x))), "% positive": (x > 0).mean() * 100})
    cs = pd.DataFrame(rows)
    cs.to_csv(OUT / "car_summary.csv", index=False)
    L += ["## 5. Cumulative abnormal returns (market model)", "",
          "Unconditional averages across all events. They are expected to be near zero: the hypothesis is about how "
          "CARs vary with sentiment, which is Stage 4.", ""] + md(cs) + [""]
    L += ["![Distribution of the two headline CARs](../results/stage2/figures/car_hist.png)", ""]
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.4))
    for ax, col, ttl in zip(axes, ["car_0_1", "car_1_5"], ["Reaction: CAR[0, +1]", "Drift: CAR[+1, +5]"]):
        x = cars[col].dropna() * 100
        ax.hist(x, bins=np.arange(-27, 27.5, 1), color=COLOR["pre-open"], edgecolor=SURFACE, linewidth=0.8)
        ax.axvline(0, color=INK2, linewidth=1)
        ax.set_title(f"{ttl} (n = {len(x)}, std {x.std():.1f}%)")
        ax.set_xlabel("percent")
    axes[0].set_ylabel("events")
    fig.tight_layout()
    fig.savefig(FIG / "car_hist.png", dpi=150)
    plt.close(fig)

    # ---- 6 model agreement ----------------------------------------------------------
    rows = []
    for col in ("car_0_1", "car_1_5"):
        rows.append({"window": col, "n ff4": int(cars[f"{col}_ff4"].notna().sum()), "n sector": int(cars[f"{col}_sector"].notna().sum()),
                     "corr market vs ff4": cars[col].corr(cars[f"{col}_ff4"]),
                     "corr market vs sector": cars[col].corr(cars[f"{col}_sector"]),
                     "std market (%)": cars[col].std() * 100, "std ff4 (%)": cars[f"{col}_ff4"].std() * 100,
                     "std sector (%)": cars[f"{col}_sector"].std() * 100})
    L += ["## 6. Agreement between expected-return models", ""] + md(pd.DataFrame(rows), "{:.3f}") + ["",
          f"Sector-model events with fewer than {es.EST_MIN_OBS} estimation observations: "
          f"{int((~cars['est_ok_sector'].fillna(False).astype(bool)).sum())} "
          "(the Communication Services ETF only started trading in June 2018).", ""]

    (config.DOCS / "stage2_event_study.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
