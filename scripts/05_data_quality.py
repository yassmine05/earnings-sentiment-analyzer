"""Stage 1, step 5: write docs/stage1_data_quality.md from the Stage 1 outputs.

Every number in the report is computed here from files produced by steps 1-4.
"""
from __future__ import annotations

import pandas as pd
import pandas_market_calendars as mcal

from earnings_sentiment import config

OUT = config.RESULTS / "stage1"


def md_table(df: pd.DataFrame) -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda x: "" if pd.isna(x) else f"{x:,.1f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|"
    body = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep] + body)


def main() -> None:
    basket = pd.read_csv(OUT / "basket.csv")
    margins = pd.read_csv(OUT / "basket_cutoff_margins.csv")
    allf = pd.read_csv(config.INTERIM / "filings_all.csv")
    sel = pd.read_csv(OUT / "events_selected.csv")
    drop = pd.read_csv(OUT / "events_dropped.csv")
    cov = pd.read_csv(OUT / "price_coverage.csv")
    spy = pd.read_csv(OUT / "spy_vs_ff_market.csv").iloc[0]
    sessions = mcal.get_calendar("NYSE").schedule(config.PRICE_START, config.PRICE_END).index.normalize()

    in_win = allf[allf["accepted_et_date"].between(config.SAMPLE_START, config.SAMPLE_END)]
    L: list[str] = []
    L += ["# Stage 1: data-quality report", "",
          "Generated by `scripts/05_data_quality.py`. Every number below is computed from the Stage 1 output files.", ""]

    # 1 basket
    L += ["## 1. Basket", "",
          f"{len(basket)} firms, {basket['sector'].nunique()} sectors, {config.FIRMS_PER_SECTOR} per sector. "
          "Membership and sector come from the Select Sector SPDR Trust N-Q (holdings at 2018-12-31). "
          "Market cap is approximate: cover-page shares outstanding times the 2018-12-31 price implied by the same N-Q.", ""]
    b = basket[["sector", "rank_in_sector", "ticker", "company_2018", "market_cap_bn", "shares_date"]].copy()
    b["shares_from"] = basket["shares_source"].str.startswith("XBRL").map({True: "XBRL", False: "hand-checked"})
    L += [md_table(b), "",
          f"Share counts: {int((b['shares_from'] == 'XBRL').sum())} from XBRL, "
          f"{int((b['shares_from'] == 'hand-checked').sum())} hand-checked from the cover page (multi-class firms).", "",
          "Margin between the 5th firm (in) and the 6th (out). Small gaps are within the error of the approximation:", "",
          md_table(margins), ""]

    # 2 filings
    L += ["## 2. Earnings filings (8-K Item 2.02)", "",
          f"- Sample window: accepted by EDGAR between {config.SAMPLE_START} and {config.SAMPLE_END} (Eastern time).",
          f"- Item 2.02 filings found in the window: **{len(in_win)}** across {in_win['ticker'].nunique()} firms.",
          f"- Kept as quarterly earnings releases: **{len(sel)}**, of which {int(sel['gap_fill'].sum())} are hand-reviewed "
          f"releases filed without Item 2.02. Dropped Item 2.02 filings: **{len(drop)}** (see `docs/stage1_event_rule.md`).",
                    f"- Kept events without a usable exhibit: {int((sel['exhibit_url'].isna() | (sel['exhibit_url'] == '')).sum())}.", ""]
    sel["quarter"] = pd.PeriodIndex(pd.to_datetime(sel["accepted_et_date"]), freq="Q").astype(str)
    grid = sel.pivot_table(index="ticker", columns="quarter", values="accession", aggfunc="count").reindex(basket["ticker"])
    all_q = [str(p) for p in pd.period_range(config.SAMPLE_START, config.SAMPLE_END, freq="Q")]
    grid = grid.reindex(columns=all_q).fillna(0).astype(int)
    per_firm = pd.DataFrame({
        "ticker": grid.index,
        "events_kept": grid.sum(axis=1).values,
        "quarters_with_0": [", ".join(q for q in all_q if grid.loc[t, q] == 0) for t in grid.index],
        "quarters_with_2+": [", ".join(q for q in all_q if grid.loc[t, q] > 1) for t in grid.index],
    })
    n_ok = int(((per_firm["events_kept"] == len(all_q)) & (per_firm["quarters_with_0"] == "")).sum())
    L += [f"Coverage by calendar quarter of release ({len(all_q)} quarters): {n_ok} of {len(basket)} firms have exactly one kept "
          "release in every quarter. Firms that deviate:", ""]
    dev = per_firm[(per_firm["quarters_with_0"] != "") | (per_firm["quarters_with_2+"] != "")]
    L += [md_table(dev) if len(dev) else "None.", "",
          "A quarter with 0 next to a quarter with 2 usually means a release slipped across a quarter boundary, "
          "not a missing release. The fiscal-period check below is the stricter test.", ""]
    fp = sel.groupby("ticker")["fiscal_period_end"].agg(["count", "nunique"]).reindex(basket["ticker"])
    L += [f"Distinct fiscal periods per firm: min {int(fp['nunique'].min())}, median {int(fp['nunique'].median())}, "
          f"max {int(fp['nunique'].max())}. Duplicate fiscal periods among kept events: {int((fp['count'] - fp['nunique']).sum())}.", ""]

    # 3 timing
    sel["bucket"] = sel["event_bucket"]
    tb = sel["bucket"].value_counts().rename_axis("timing bucket").reset_index(name="events")
    tb["share_%"] = (tb["events"] / len(sel) * 100).round(1)
    L += ["## 3. Timing split (event clock, Eastern)", "",
          "Pre-open is before 09:30, market hours 09:30 to 15:59, after close 16:00 or later, all on NYSE trading days.", "",
          md_table(tb), ""]
    firm_bucket = sel.pivot_table(index="ticker", columns="bucket", values="accession", aggfunc="count").fillna(0).astype(int)
    firm_bucket = firm_bucket.reindex(basket["ticker"]).reset_index()
    L += ["Per firm:", "", md_table(firm_bucket), "",
          "Acceptance time is when EDGAR accepted the 8-K, which can lag the newswire release. "
          "Stage 2 tests this with the abnormal-return and abnormal-volume plots by bucket.", ""]

    # 4 text
    w = sel["words_prose"].dropna()
    q = w.quantile([0.05, 0.25, 0.5, 0.75, 0.95]).round(0).astype(int)
    L += ["## 4. Exhibit text", "",
          f"Prose word count per kept exhibit, financial tables removed (n = {len(w)}): "
          f"min {int(w.min())}, 5% {q[0.05]}, 25% {q[0.25]}, median {q[0.5]}, 75% {q[0.75]}, 95% {q[0.95]}, max {int(w.max())}.", "",
          f"Exhibits with fewer than 200 prose words: {int((w < 200).sum())}.", ""]
    ex = sel["exhibit_type"].fillna("none").value_counts().rename_axis("exhibit type").reset_index(name="events")
    L += [md_table(ex), ""]
    short = sel[sel["words_prose"] < 200][["ticker", "accepted_et_date", "exhibit_type", "words_prose", "words_full"]]
    if len(short):
        L += ["Short exhibits (candidates for a different exhibit choice in Stage 3):", "", md_table(short), ""]

    # 5 prices
    stocks = cov[cov["ticker"].isin(basket["ticker"])]
    L += ["## 5. Prices and factors", "",
          f"- Source: Yahoo Finance via yfinance, {config.PRICE_START} to {config.PRICE_END}.",
          f"- Basket firms with a full history ({int(stocks['expected_sessions_full_window'].max())} NYSE sessions): "
          f"{int((stocks['rows'] == stocks['expected_sessions_full_window']).sum())} of {len(stocks)}.",
          f"- Firms with no price history (dropped): {int((stocks['rows'] == 0).sum())}.",
          f"- Missing sessions inside any ticker's span: {int(cov['missing_sessions_inside_span'].sum())}. "
          f"Null adjusted closes: {int(cov['null_adj_close'].sum())}. Zero-volume days: {int(cov['zero_volume_days'].sum())}.",
          f"- XLC (Communication Services ETF) starts {cov.loc[cov['ticker'] == 'XLC', 'first'].iloc[0]}, "
          "so the sector-ETF robustness benchmark is unavailable for that sector's earliest estimation windows.",
          f"- Fama-French daily factors cover the full window. SPY daily return vs Ken French market return over "
          f"{int(spy['n_days'])} days: correlation {spy['correlation']:.4f}, mean absolute difference "
          f"{spy['mean_abs_diff_bp']:.1f} bp, maximum {spy['max_abs_diff_bp']:.1f} bp.", ""]
    frames = [pd.read_parquet(config.PRICES_DIR / f"{t}.parquet") for t in basket["ticker"]]
    px = pd.concat(frames, ignore_index=True).sort_values(["ticker", "date"])
    px["ret"] = px.groupby("ticker")["adj_close"].pct_change()
    px["raw_ret"] = px.groupby("ticker")["close"].pct_change()
    big = px[px["ret"].abs() > 0.15].copy()
    ev_dates = sel.groupby("ticker")["accepted_et_date"].apply(lambda s: pd.to_datetime(s).tolist()).to_dict()
    big["days_to_nearest_event"] = [
        min((abs((d - e).days) for e in ev_dates.get(t, [])), default=None) for t, d in zip(big["ticker"], big["date"])
    ]
    big["date"] = big["date"].dt.date
    big["ret_%"] = (big["ret"] * 100).round(1)
    big["unadjusted_ret_%"] = (big["raw_ret"] * 100).round(1)
    L += [f"Daily adjusted returns larger than 15% in absolute value ({len(big)} firm-days), listed to catch bad "
          "split or spin-off adjustments:", "",
          md_table(big[["ticker", "date", "ret_%", "unadjusted_ret_%", "days_to_nearest_event"]]) if len(big) else "None.", ""]
    sp = px[(px["split"].fillna(0) != 0)][["ticker", "date", "split"]].copy()
    sp["date"] = sp["date"].dt.date
    L += [f"Stock splits recorded by Yahoo in the window: {len(sp)}.", "", md_table(sp) if len(sp) else "", ""]

    (config.DOCS / "stage1_data_quality.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
