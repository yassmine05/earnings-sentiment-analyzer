"""Stage 1, step 6: find stock-specific price jumps and corporate-action days, and fix the list of
days excluded from estimation windows.

Scan 1  days where |stock return| > 15% while |SPY return| < 3%
Scan 2  every split / spin-off record Yahoo holds for the basket

Each row is joined to a hand-written verdict in data/reference/. A scan row without a verdict stops the script.

Outputs  results/stage1/price_jump_review.csv, results/stage1/corporate_action_review.csv,
         results/stage1/price_excluded_days.csv, docs/stage1_price_artifacts.md
"""
from __future__ import annotations

import pandas as pd

from earnings_sentiment import config

OUT = config.RESULTS / "stage1"
SECTOR_ETF = {
    "Communication Services": "XLC", "Consumer Discretionary": "XLY", "Consumer Staples": "XLP", "Energy": "XLE",
    "Financials": "XLF", "Health Care": "XLV", "Industrials": "XLI", "Information Technology": "XLK",
    "Materials": "XLB", "Real Estate": "XLRE", "Utilities": "XLU",
}
STOCK_JUMP, MARKET_QUIET = 0.15, 0.03


def load(ticker: str) -> pd.DataFrame:
    d = pd.read_parquet(config.PRICES_DIR / f"{ticker}.parquet").set_index("date")
    d["ret"] = d["adj_close"].pct_change()
    return d


def md(df: pd.DataFrame) -> list[str]:
    out = ["| " + " | ".join(df.columns) + " |", "|" + "|".join(["---"] * len(df.columns)) + "|"]
    for row in df.itertuples(index=False):
        out.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return out


def main() -> None:
    basket = pd.read_csv(OUT / "basket.csv")
    events = pd.read_csv(OUT / "events_selected.csv")
    day0 = events.groupby("ticker")["event_day0"].apply(lambda s: pd.to_datetime(s).tolist()).to_dict()
    spy = load("SPY")["ret"]
    sessions = spy.index

    def trading_days_to_event(ticker, date):
        """Signed trading-day distance to the nearest event: 0 = day 0, +1 = the session after, etc."""
        pos = sessions.get_loc(date)
        gaps = [pos - sessions.get_loc(e) for e in day0.get(ticker, []) if e in sessions]
        return min(gaps, key=abs) if gaps else None

    jumps, actions = [], []
    for b in basket.itertuples():
        d = load(b.ticker)
        etf = load(SECTOR_ETF[b.sector])["ret"]
        for dt, x in d.iterrows():
            is_jump = abs(x["ret"]) > STOCK_JUMP and abs(spy.get(dt, float("nan"))) < MARKET_QUIET
            is_action = x["split"] != 0
            if not (is_jump or is_action):
                continue
            row = {
                "ticker": b.ticker, "date": dt.date().isoformat(),
                "stock_ret_%": round(x["ret"] * 100, 1), "spy_ret_%": round(spy[dt] * 100, 1),
                "sector_etf_ret_%": round(etf[dt] * 100, 1) if dt in etf.index and pd.notna(etf[dt]) else None,
                "trading_days_from_nearest_event": trading_days_to_event(b.ticker, dt),
                "yahoo_split_record": x["split"] if is_action else "",
            }
            if is_jump:
                jumps.append(row)
            if is_action:
                actions.append(row)

    jumps, actions = pd.DataFrame(jumps), pd.DataFrame(actions)
    jr = pd.read_csv(config.REFERENCE / "price_jump_review.csv")
    ar = pd.read_csv(config.REFERENCE / "corporate_action_review.csv")
    jumps = jumps.merge(jr, on=["ticker", "date"], how="left")
    actions = actions.merge(ar, on=["ticker", "date"], how="left")
    for name, df, col in (("jump", jumps, "verdict"), ("corporate action", actions, "kind")):
        missing = df[df[col].isna()]
        if len(missing):
            raise SystemExit(f"{name} rows without a hand review:\n{missing[['ticker', 'date']].to_string()}")
    jumps.to_csv(OUT / "price_jump_review.csv", index=False)
    actions.to_csv(OUT / "corporate_action_review.csv", index=False)

    excl = pd.concat([
        jumps.loc[jumps["verdict"] == "artifact", ["ticker", "date"]].assign(reason="unverifiable jump on a corporate-action day"),
        actions.loc[actions["exclude_from_estimation"], ["ticker", "date"]].assign(reason="spin-off or merger adjustment day"),
    ]).drop_duplicates(["ticker", "date"]).sort_values(["ticker", "date"]).reset_index(drop=True)
    td = [trading_days_to_event(t, pd.Timestamp(d)) for t, d in zip(excl["ticker"], excl["date"])]
    excl["trading_days_from_nearest_event"] = td
    excl["inside_event_window_m1_p5"] = [(-1 <= x <= 5) if x is not None else False for x in td]
    excl.to_csv(OUT / "price_excluded_days.csv", index=False)

    L = ["# Stage 1: price jumps and corporate-action days", "",
         "Generated by `scripts/06_price_artifacts.py`. Returns and distances are computed from the price files. "
         "The verdict and explanation columns are written by hand in `data/reference/` from the public record of each "
         "event; they are judgements, not outputs of the code.", "",
         f"## Scan 1: |stock return| > {STOCK_JUMP:.0%} while |SPY return| < {MARKET_QUIET:.0%}", "",
         f"{len(jumps)} firm-days across the 55 firms, {config.PRICE_START} to {config.PRICE_END}. "
         f"Verdicts: {jumps['verdict'].value_counts().to_dict()}.", "",
         "`trading_days_from_nearest_event`: 0 is the event's day 0, +1 the next session, negative values are before it.", ""]
    L += md(jumps[["ticker", "date", "stock_ret_%", "spy_ret_%", "sector_etf_ret_%", "trading_days_from_nearest_event",
                   "yahoo_split_record", "verdict", "explanation"]])
    n_evt = int(jumps["trading_days_from_nearest_event"].isin([0, 1]).sum())
    L += ["", f"{n_evt} of the {len(jumps)} jumps fall on day 0 or day +1 of one of the sample's own earnings events.", "",
          "## Scan 2: every split and spin-off record Yahoo holds for the basket", "",
          "Ordinary splits are adjusted exactly and need no action. Yahoo models spin-offs and mergers as a non-integer "
          "split, which is an approximation: the stock return on those days depends on the value Yahoo assigned to the "
          "distributed shares and cannot be checked without a second price source. Those days are excluded from "
          "estimation windows as a precaution, whether or not the return looks unusual.", ""]
    L += md(actions[["ticker", "date", "yahoo_split_record", "stock_ret_%", "spy_ret_%", "sector_etf_ret_%",
                     "trading_days_from_nearest_event", "kind", "exclude_from_estimation", "explanation"]])
    L += ["", "General Electric, given as an example of a firm with splits and spin-offs, is not in the basket "
          "(it ranks 8th by market cap in Industrials at 2018-12-31).", "",
          "## Days excluded from estimation windows", "",
          f"{len(excl)} firm-days. Excluding a day means the stock's return on that day is not used to estimate "
          "the market model; the following day's return is unaffected because returns are computed before the exclusion.", ""]
    L += md(excl)
    n_in = int(excl["inside_event_window_m1_p5"].sum())
    L += ["", f"Excluded days that fall inside an event window [-1, +5]: **{n_in}**. "
          + ("These events are flagged in Stage 2." if n_in else "No event window is affected."), ""]
    (config.DOCS / "stage1_price_artifacts.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
